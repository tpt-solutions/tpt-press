//! Chunk boundaries for streaming pack: fixed-size, or content-defined.
//!
//! Fixed-size chunks are simple, but one inserted byte shifts every later
//! boundary, so every later chunk changes. Content-defined chunks end where a
//! rolling hash of the recent bytes hits a pattern. An insertion then moves only
//! the boundaries near it, and the chunks further on are unchanged. That helps
//! deduplication and delta storage between versions of a file.
//!
//! The boundary search uses the gear hash, as in FastCDC. Boundaries depend only
//! on the bytes, so the same input gives the same chunks however it is read.

use std::io::{self, Read};

use crate::archive::MAX_CHUNK_SIZE;

/// How a stream is split into chunks.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Chunking {
    /// Every chunk is `chunk_size` bytes, except the last.
    #[default]
    Fixed,
    /// Chunk ends depend on the content. `chunk_size` is the average size.
    /// Chunks are between a quarter and four times the average.
    ContentDefined,
}

/// Smallest average size for content-defined chunks.
pub const MIN_AVERAGE_CHUNK: usize = 256;

/// Largest average for content-defined chunks. The largest chunk is four times
/// the average, and must fit in a frame.
pub const MAX_AVERAGE_CHUNK: usize = MAX_CHUNK_SIZE / 4;

/// Parameters of the content-defined splitter, derived from the average size.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Cdc {
    min: usize,
    max: usize,
    /// Right shift that leaves the top `bits` bits of the hash.
    shift: u32,
}

impl Cdc {
    /// Parameters for an average of `average` bytes. The average must be a
    /// power of two in `MIN_AVERAGE_CHUNK..=MAX_AVERAGE_CHUNK`.
    pub(crate) fn new(average: usize) -> Self {
        let bits = average.trailing_zeros();
        Self {
            min: average / 4,
            max: average * 4,
            shift: 64 - bits,
        }
    }
}

/// The gear table: 256 pseudo-random 64-bit values, one per byte value.
/// Generated by a fixed SplitMix64 sequence, so boundaries are the same on
/// every platform and release.
const GEAR: [u64; 256] = gear_table();

const fn gear_table() -> [u64; 256] {
    let mut table = [0u64; 256];
    let mut state: u64 = 0;
    let mut i = 0;
    while i < 256 {
        state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = state;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        table[i] = z ^ (z >> 31);
        i += 1;
    }
    table
}

/// Length of the chunk that starts `window`. `window` must hold at least
/// `cdc.max` bytes, or the rest of the input.
fn cut_point(window: &[u8], cdc: Cdc) -> usize {
    let limit = window.len().min(cdc.max);
    if limit <= cdc.min {
        return limit;
    }
    let mut hash: u64 = 0;
    for (i, &byte) in window[..limit].iter().enumerate() {
        hash = (hash << 1).wrapping_add(GEAR[usize::from(byte)]);
        // The first `min` bytes can never end a chunk, so skip the test there.
        if i + 1 > cdc.min && hash >> cdc.shift == 0 {
            return i + 1;
        }
    }
    limit
}

/// Reads a stream as a sequence of chunks, one at a time.
pub(crate) struct Splitter<R> {
    input: R,
    /// Bytes read but not yet made into chunks.
    pending: Vec<u8>,
    eof: bool,
    mode: Mode,
}

#[derive(Clone, Copy)]
enum Mode {
    Fixed(usize),
    Content(Cdc),
}

/// Bytes read at a time from the input. A small read keeps memory in check.
const READ_STEP: usize = 64 * 1024;

impl<R: Read> Splitter<R> {
    /// A splitter for `chunking`. `chunk_size` is the fixed size, or the average
    /// for content-defined chunks. The caller checks that it is in range.
    pub(crate) fn new(input: R, chunking: Chunking, chunk_size: usize) -> Self {
        let mode = match chunking {
            Chunking::Fixed => Mode::Fixed(chunk_size),
            Chunking::ContentDefined => Mode::Content(Cdc::new(chunk_size)),
        };
        Self {
            input,
            pending: Vec::new(),
            eof: false,
            mode,
        }
    }

    /// The most bytes one chunk can take. Enough pending bytes are kept to find its end.
    fn window(&self) -> usize {
        match self.mode {
            Mode::Fixed(size) => size,
            Mode::Content(cdc) => cdc.max,
        }
    }

    /// Reads until `pending` holds `want` bytes or the input ends.
    fn fill(&mut self, want: usize) -> io::Result<()> {
        let mut step = vec![0u8; READ_STEP];
        while !self.eof && self.pending.len() < want {
            match self.input.read(&mut step) {
                Ok(0) => self.eof = true,
                Ok(n) => self.pending.extend_from_slice(&step[..n]),
                Err(e) if e.kind() == io::ErrorKind::Interrupted => {}
                Err(e) => return Err(e),
            }
        }
        Ok(())
    }

    /// The next chunk, or `None` at the end of the input.
    pub(crate) fn next_chunk(&mut self) -> io::Result<Option<Vec<u8>>> {
        let window = self.window();
        self.fill(window)?;
        if self.pending.is_empty() {
            return Ok(None);
        }
        let len = match self.mode {
            Mode::Fixed(size) => size.min(self.pending.len()),
            Mode::Content(cdc) => cut_point(&self.pending, cdc),
        };
        Ok(Some(self.pending.drain(..len).collect()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Yields its bytes in pieces of `step`, to show that reads do not change the chunks.
    struct Trickle<'a> {
        data: &'a [u8],
        step: usize,
    }

    impl Read for Trickle<'_> {
        fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
            let n = self.step.min(buf.len()).min(self.data.len());
            buf[..n].copy_from_slice(&self.data[..n]);
            self.data = &self.data[n..];
            Ok(n)
        }
    }

    fn chunks(data: &[u8], chunking: Chunking, size: usize) -> Vec<Vec<u8>> {
        let mut splitter = Splitter::new(data, chunking, size);
        let mut out = Vec::new();
        while let Some(chunk) = splitter.next_chunk().unwrap() {
            out.push(chunk);
        }
        out
    }

    /// Pseudo-random bytes, so chunk boundaries have no structure to exploit.
    fn noise(len: usize, seed: u64) -> Vec<u8> {
        let mut x = seed | 1;
        (0..len)
            .map(|_| {
                x ^= x << 13;
                x ^= x >> 7;
                x ^= x << 17;
                (x >> 24) as u8
            })
            .collect()
    }

    #[test]
    fn fixed_chunks_are_the_requested_size() {
        let data = noise(10_000, 1);
        let parts = chunks(&data, Chunking::Fixed, 4096);
        let lens: Vec<usize> = parts.iter().map(Vec::len).collect();
        assert_eq!(lens, [4096, 4096, 1808]);
        assert_eq!(parts.concat(), data);
    }

    #[test]
    fn content_chunks_respect_their_bounds() {
        let average = 4096;
        let data = noise(400_000, 2);
        let parts = chunks(&data, Chunking::ContentDefined, average);
        assert_eq!(parts.concat(), data);
        for (i, part) in parts.iter().enumerate() {
            assert!(part.len() <= average * 4);
            // Only the last chunk may be shorter than the minimum.
            if i + 1 < parts.len() {
                assert!(
                    part.len() > average / 4,
                    "chunk {i} is {} bytes",
                    part.len()
                );
            }
        }
    }

    #[test]
    fn read_sizes_do_not_change_the_chunks() {
        let data = noise(300_000, 3);
        let whole = chunks(&data, Chunking::ContentDefined, 8192);
        for step in [1, 7, 4096, 100_000] {
            let mut splitter = Splitter::new(
                Trickle { data: &data, step },
                Chunking::ContentDefined,
                8192,
            );
            let mut got = Vec::new();
            while let Some(chunk) = splitter.next_chunk().unwrap() {
                got.push(chunk);
            }
            assert_eq!(got, whole, "read step {step}");
        }
    }

    #[test]
    fn an_insertion_only_disturbs_nearby_chunks() {
        let original = noise(600_000, 4);
        let mut edited = b"a short note inserted at the front".to_vec();
        edited.extend_from_slice(&original);

        let a = chunks(&original, Chunking::ContentDefined, 4096);
        let b = chunks(&edited, Chunking::ContentDefined, 4096);
        let shared = a.iter().filter(|c| b.contains(c)).count();
        assert!(
            shared * 10 >= a.len() * 9,
            "only {shared} of {} chunks survived the insertion",
            a.len()
        );

        // Fixed-size chunks all shift, so almost nothing is shared.
        let fa = chunks(&original, Chunking::Fixed, 4096);
        let fb = chunks(&edited, Chunking::Fixed, 4096);
        let fixed_shared = fa.iter().filter(|c| fb.contains(c)).count();
        assert!(fixed_shared * 10 < fa.len(), "{fixed_shared} shared");
    }

    #[test]
    fn empty_input_has_no_chunks() {
        assert!(chunks(&[], Chunking::ContentDefined, 1024).is_empty());
        assert!(chunks(&[], Chunking::Fixed, 1024).is_empty());
    }
}
